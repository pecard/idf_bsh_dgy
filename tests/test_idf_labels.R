suppressPackageStartupMessages(library(data.table))
source("R/idf_labels.R")
codes_test <- c("GW32-22", "GW25-24", "GW32-22", "", NA, "GW19-13")
m_test <- build_idf_label_map(codes_test, c("GW40-26"))
stopifnot(identical(unname(m_test[c("IDF13", "IDF22", "IDF24", "IDF26")]), c("GW19-13", "GW32-22", "GW25-24", "GW40-26")))
stopifnot(identical(relabel_idf(c("IDF22", "IDF99", "GW19-13"), m_test), c("GW32-22", "IDF99", "GW19-13")))
f_test <- relabel_idf(factor(c("IDF22", "IDF24")), m_test)
stopifnot(is.factor(f_test), identical(as.character(f_test), c("GW32-22", "GW25-24")))
d_test <- relabel_idf_cols(data.table(idf = c("IDF13", "IDF22"), x = 1:2), m_test)
stopifnot(identical(d_test$idf, c("GW19-13", "GW32-22")))
# settings tem precedencia sobre o deduzido
m2_test <- build_idf_label_map(c("GW32-22"), c("GWXX-22"))
stopifnot(m2_test[["IDF22"]] == "GWXX-22")
# BSH/DGY: codigos ja' completos
m3_test <- build_idf_label_map(c("BSH55-09", "DZH01-01"))
stopifnot(identical(names(m3_test), c("IDF01", "IDF09")))
tb_test <- idf_label_table(m_test); stopifnot(all(c("unit_number", "internal_label", "full_name") %in% names(tb_test)))
cat("test_idf_labels OK\n")

